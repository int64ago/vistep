export function genomesDirector(chapter: number, time: number, locale = 'zh') {
  const c = Math.min(3, Math.max(0, Math.floor(finite(chapter)))),
    q = Math.max(0, finite(time));
  const en = locale === 'en',
    a = genomeMeasuredAnchors[en ? 'en' : 'zh'];
  if (c === 0)
    return {
      chapter: c,
      shot:
        q < a.markers
          ? 'colonies'
          : q < a.assembly
            ? 'markers'
            : q < a.dnaAlone
              ? 'assembly'
              : 'dna-alone',
      assembly: smoothWindow(q, a.assembly, a.ringComplete),
      expressionTime: 0,
      fusions: 0,
      revealHours: 0,
    };
  if (c === 1) {
    const anchors: readonly (readonly [number, number])[] = en
      ? [
          [9.9, 0],
          [12.2, 1],
          [16, 7],
          [16.4, 8],
          [19, 9],
          [21.2, 15],
          [23.2, 17],
          [24.9, 18],
          [27.45, 23.9],
          [27.7, 25],
          [28.4, 28],
          [32.9, 29],
        ]
      : [
          [8.6, 0],
          [11.3, 1],
          [14.9, 7],
          [15.1, 8],
          [17.6, 9],
          [20, 15],
          [22, 17],
          [24.3, 18],
          [28.2, 23.9],
          [28.8, 25],
          [29.5, 28],
          [34.4, 29],
        ];
    return {
      chapter: c,
      shot:
        q < a.transcription
          ? 'cell'
          : q < a.translation
            ? 'transcription'
            : q < a.reporter
              ? 'translation'
              : q < a.counterexample
                ? 'reporter'
                : 'counterexample',
      assembly: 1,
      expressionTime: q < a.counterexample ? expressionClock(q, anchors) : 0,
      fusions: 0,
      revealHours: 0,
    };
  }
  if (c === 2)
    return {
      chapter: c,
      shot: q < a.fusionStart ? 'yeast' : q < a.fusionEnd ? 'fusion' : 'one-chromosome',
      assembly: 1,
      expressionTime: 0,
      fusions: 15 * smoothWindow(q, a.fusionStart, a.fusionEnd),
      revealHours: 0,
    };
  return {
    chapter: c,
    shot: q < a.prediction ? 'growth' : q < a.answer ? 'predict' : 'answer',
    assembly: 1,
    expressionTime: 0,
    fusions: 15,
    // A fixed early prefix supports axis reading; later published points wait for the spoken reveal.
    revealHours: 6 + 20 * smoothWindow(q, a.revealStart, a.revealEnd),
  };
}
/** Representative object geometry; IDs refer to material, never the displayed color. */
export function rnaGeometry(fraction: number, translation = false) {
  const f = bound(fraction);
  return Array.from({ length: 17 }, (_, id) => {
    const u = id / 16;
    return {
      id: `RNA-1-${id}`,
      x: translation ? 26 + 248 * u : 139 + 118 * u,
      y: translation ? 67 : 89 - 49 * u + 7 * Math.sin(u * Math.PI * 2),
      visible: u <= f && f > 0,
    };
  });
}
export function proteinGeometry(fraction: number, release: number) {
  const f = bound(fraction),
    r = bound(release),
    material = f * 16;
  return Array.from({ length: 16 }, (_, id) => {
    const joined = material >= id + 1,
      arrival = smooth(material - id);
    // Earlier residues move out as the newest residue joins at the ribosome exit.
    const distance = Math.max(0, material - id - 1),
      cx = 159 + 15 * Math.sin(distance * 0.6),
      cy = 119 + 5.7 * distance;
    const sx = 247 + (id % 3) * 11,
      sy = 110 + Math.floor(id / 3) * 12;
    const x = joined ? cx : sx + (159 - sx) * arrival,
      y = joined ? cy : sy + (119 - sy) * arrival;
    const u = id / 15,
      theta = u * Math.PI * 4,
      fx = 213 + (12 + 14 * u) * Math.cos(theta),
      fy = 166 + (9 + 11 * u) * Math.sin(theta);
    return {
      id: `protein-1-aa-${id}`,
      x: x + (fx - x) * r,
      y: y + (fy - y) * r,
      visible: joined,
      attached: joined,
    };
  });
}
