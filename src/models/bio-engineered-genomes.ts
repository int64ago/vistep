export const smoothWindow = (time: number, from: number, to: number) =>
  smooth((finite(time) - from) / (to - from));
export type ExpressionInputs = {
  polymerase?: boolean;
  ribosome?: boolean;
  resources?: boolean;
  preexistingRna?: boolean;
  substrate?: boolean;
};
/** Teaching event order, not measured kinetics. Retained templates and new matter have different IDs.
 * No RNA polymerase now is compatible with translation of an already present RNA.
 */
export function expressionState(time: number, inputs: ExpressionInputs = {}) {
  const q = Math.max(0, finite(time)),
    {
      polymerase = true,
      ribosome = true,
      resources = true,
      preexistingRna = false,
      substrate = true,
    } = inputs;
  const rnaFraction = preexistingRna ? 1 : polymerase && resources ? smoothWindow(q, 1, 7) : 0;
  const proteinFraction = rnaFraction === 1 && ribosome && resources ? smoothWindow(q, 9, 15) : 0;
  const proteinRelease = proteinFraction === 1 ? smoothWindow(q, 15, 17) : 0;
  const ready = proteinRelease === 1 && substrate;
  const events = [0, 1].map((id) => {
    const at = 18 + id * 3.1;
    const approach = ready ? smoothWindow(q, at, at + 1) : 0;
    const cut = ready ? smoothWindow(q, at + 1, at + 1.4) : 0;
    const release = ready ? smoothWindow(q, at + 1.4, at + 2.8) : 0;
    return {
      id,
      substrateId: `substrate-${id}`,
      intermediateId: `indoxyl-unit-${id}`,
      sugarId: `sugar-${id}`,
      approach,
      cut,
      release,
    };
  });
  // Both released precursor units precede the blue dimer. Oxidation/other steps are merged,
  // not represented as a balanced elementary reaction or a quantitative color assay.
  const pigment = events.every((e) => e.release === 1) ? smoothWindow(q, 25, 28) : 0;
  return {
    time: q,
    dnaId: 'DNA-1',
    rnaId: preexistingRna ? 'existing-RNA-1' : 'new-RNA-1',
    proteinId: 'protein-1',
    machineryIds: [...(polymerase ? ['polymerase-1'] : []), ...(ribosome ? ['ribosome-1'] : [])],
    rnaFraction,
    proteinFraction,
    proteinRelease,
    events,
    pigment,
    substratePresent: substrate,
    predictsViability: null,
    stage: proteinFraction > 0 ? 'protein' : rnaFraction > 0 ? 'rna' : 'dna',
  };
}
/** Sixteen representative regions are regrouped along an actual continuous serpentine path.
 * Each region retains material path length; disappearing gaps are boundary-sequence symbols.
 */
export function foldedFusion(fusions: number) {
  const f = Math.max(0, Math.min(15, finite(fusions))),
    n = Math.floor(f),
    blend = smooth(f - n);
  const gap = (after: number) => (after < n ? 0 : after === n ? 6 * (1 - blend) : 6);
  const distanceBefore = (id: number) =>
    id * 12 + Array.from({ length: id }, (_, j) => gap(j)).reduce((a, b) => a + b, 0);
  // Rounded serpentine routing is parameterized separately from data grouping.
  const route = (d: number) => {
    const arcUnits = (Math.PI * 26) / 2.75,
      span = 64 + arcUnits,
      row = Math.floor(d / span),
      u = d - row * span;
    if (u <= 64) return { x: row % 2 === 0 ? 54 + u * 2.75 : 230 - u * 2.75, y: 52 + row * 52 };
    const theta = ((u - 64) / arcUnits) * Math.PI;
    return {
      x: (row % 2 === 0 ? 230 : 54) + (row % 2 === 0 ? 1 : -1) * 26 * Math.sin(theta),
      y: 52 + row * 52 + 26 * (1 - Math.cos(theta)),
    };
  };
  const blocks = Array.from({ length: 16 }, (_, id) => ({
    id,
    points: Array.from({ length: 13 }, (_, j) => route(distanceBefore(id) + j)),
    centromereOpacity: id === 0 ? 1 : id <= n ? 0 : id === n + 1 ? 1 - blend : 1,
  }));
  const joins = Array.from({ length: 15 }, (_, i) => ({
    id: i,
    opacity: i < n ? 1 : i === n ? blend : 0,
    points: Array.from({ length: 8 }, (_, j) =>
      route(distanceBefore(i) + 12 + ((distanceBefore(i + 1) - distanceBefore(i) - 12) * j) / 7),
    ),
  }));
  return { blocks, joins, chromosomes: 16 - n, completed: n === 15, trace: blocks[6].points[6] };
}
/** Piecewise teaching time derived from measured speech, never biological kinetic time.
 * The visible object state remains continuous within an explanatory shot.
 */
function expressionClock(q: number, anchors: readonly (readonly [number, number])[]) {
  if (q <= anchors[0][0]) return anchors[0][1];
  for (let i = 1; i < anchors.length; i++) {
    const [t, state] = anchors[i],
      [previousT, previousState] = anchors[i - 1];
    if (q <= t)
      return previousState + ((state - previousState) * (q - previousT)) / (t - previousT);
  }
  return anchors.at(-1)![1];
}
