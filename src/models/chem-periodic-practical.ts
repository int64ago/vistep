export type Halogen = 'Cl' | 'Br' | 'I';
export type HydroxideMetal = 'Mg' | 'Al';
export type TestMedium = 'none' | 'acid' | 'base';
const finite = (n: number, fallback = 0) => (Number.isFinite(n) ? n : fallback);
const clamp = (n: number, lo = 0, hi = 1) => Math.max(lo, Math.min(hi, finite(n)));
const smooth = (n: number) => {
  const p = clamp(n);
  return p * p * (3 - 2 * p);
};
const span = (t: number, a: number, b: number) => smooth((t - a) / (b - a));
const mix = (a: number, b: number, p: number) => a + (b - a) * p;

