/** Directed observed comparisons induce a qualitative ordering; reverse tests are predictions. */
export function inferredHalogenOrder(records = HALOGEN_RECORDS) {
  return (['Cl', 'Br', 'I'] as Halogen[]).sort(
    (a, b) =>
      records.filter((r) => r.oxidant === b).length - records.filter((r) => r.oxidant === a).length,
  );
}
export function halogenDisplacement(
  oxidant: Halogen = 'Cl',
  halide: Halogen = 'Br',
  progress = 1,
  available = 0.5,
) {
  const order = inferredHalogenOrder(),
    input = clamp(available, 0, 0.5);
  const allowed = order.indexOf(oxidant) < order.indexOf(halide);
  const reaction = allowed ? input * clamp(progress) : 0;
  return {
    oxidant,
    halide,
    allowed,
    input,
    oxidantLeft: input - reaction,
    oxidantIon: 2 * reaction,
    halideLeft: 1 - 2 * reaction,
    product: reaction,
    electrons: 2 * reaction,
    initialOxidantAtoms: 2 * input,
    initialHalideAtoms: 1,
    charge: -1,
  };
}

export type NetAtom = {
  id: string;
  element: string;
  x: number;
  y: number;
  charge: number;
  phase: string;
};
/** One selected NET event; electrons are accounting credits, not free aqueous trajectories. */
export function halogenEvent(oxidant: Halogen, halide: Halogen, progress: number, width = 300) {
  const w = clamp(width, 260, 900),
    allowed = halogenDisplacement(oxidant, halide).allowed;
  const p = allowed ? clamp(progress) : 0,
    departed = p >= 0.2,
    arrived = p >= 0.8;
  const move = span(p, 0.2, 0.8),
    pair = span(p, 0.8, 1);
  const atoms: NetAtom[] = [0, 1].flatMap((i) => [
    {
      id: `donor-${i}`,
      element: halide,
      x: mix(w * 0.2, w * 0.2 + (i ? 13 : -13), pair),
      y: mix(65 + i * 65, 98, pair),
      charge: departed ? 0 : -1,
      phase: departed ? 'element' : 'halide',
    },
    {
      id: `acceptor-${i}`,
      element: oxidant,
      x: mix(w * 0.78 + (i ? 13 : -13), w * 0.78, pair),
      y: mix(98, 65 + i * 65, pair),
      charge: arrived ? -1 : 0,
      phase: arrived ? 'halide' : 'element',
    },
  ]);
  const electrons = [0, 1].map((i) => ({
    id: `e-${i}`,
    x: mix(w * 0.2 + 19, w * 0.78 - 20, move),
    y: 65 + i * 65 + (i ? 1 : -1) * 18 * Math.sin(Math.PI * move),
    phase: !departed ? 'donor' : !arrived ? 'transfer' : 'acceptor',
  }));
  return {
    atoms,
    electrons,
    allowed,
    departed,
    arrived,
    transferCharge: departed && !arrived ? -2 : 0,
    charge: atoms.reduce((s, a) => s + a.charge, 0) + (departed && !arrived ? -2 : 0),
  };
}

/** Extent is an illustrative net account, NEVER a rate law or cold-water zero-rate assertion. */
export function magnesiumWater(hot = true, progress = 1) {
  const reacted = hot ? clamp(progress) : 0;
  return {
    metal: 1 - reacted,
    hydroxide: reacted,
    hydrogen: reacted,
    waterUsed: 2 * reacted,
    pink: reacted > 0,
    observation: hot ? 'visible-on-heating' : 'not-obvious-in-short-observation',
    isRateModel: false,
  };
}
/** 7 persistent atom IDs for Mg + 2H2O -> Mg(OH)2 + H2. Net allocation only. */
export function magnesiumNet(progress: number, width = 300) {
  const w = clamp(width, 260, 900),
    p = clamp(progress),
    release = span(p, 0.18, 0.75),
    settle = span(p, 0.55, 1);
  const left = w * 0.22,
    right = w * 0.74;
  const atoms: NetAtom[] = [
    {
      id: 'Mg',
      element: 'Mg',
      x: mix(w * 0.48, left, settle),
      y: mix(178, 147, settle),
      charge: p >= 0.2 ? 2 : 0,
      phase: p >= 0.95 ? 'solid' : p >= 0.2 ? 'transfer' : 'metal',
    },
  ];
  for (let i = 0; i < 2; i++) {
    const sx = w * (0.27 + 0.46 * i),
      ox = left + (i ? 25 : -25),
      oy = 111;
    atoms.push({
      id: `O${i}`,
      element: 'O',
      x: mix(sx, ox, settle),
      y: mix(95, oy, settle),
      charge: -2,
      phase: p >= 0.95 ? 'solid' : 'water',
    });
    atoms.push({
      id: `H${i}-stay`,
      element: 'H',
      x: mix(sx - 16, ox - 12, settle),
      y: mix(76, oy - 20, settle),
      charge: 1,
      phase: p >= 0.95 ? 'solid' : 'water',
    });
    atoms.push({
      id: `H${i}-gas`,
      element: 'H',
      x: mix(sx + 16, right + (i ? 12 : -12), release),
      y: mix(76, 38, release),
      charge: p >= 0.75 ? 0 : 1,
      phase: p >= 0.75 ? 'gas' : 'water',
    });
  }
  const transferCharge = p >= 0.2 && p < 0.75 ? -2 : 0;
  return {
    atoms,
    transferCharge,
    charge: atoms.reduce((s, a) => s + a.charge, 0) + transferCharge,
    electronProgress: span(p, 0.2, 0.75),
    electrons: [0, 1].map((i) => ({
      id: `Mg-e-${i}`,
      x:
        mix(w * 0.48 + (i ? 10 : -10), right + (i ? 12 : -12), span(p, 0.2, 0.75)) -
        65 * Math.sin(Math.PI * span(p, 0.2, 0.75)),
      y: mix(178, 38, span(p, 0.2, 0.75)),
      phase: p < 0.2 ? 'donor' : p < 0.75 ? 'transfer' : 'acceptor',
    })),
    hydrogenReady: p >= 0.75,
    solidReady: p >= 0.95,
  };
}

/** Net amount AFTER NH3/NH4+ background reactions; not the added laboratory volume. */
export function periodHydroxide(
  metal: HydroxideMetal = 'Al',
  medium: TestMedium = 'none',
  amount = 3,
  prepared = 1,
) {
  const solid = clamp(prepared),
    input = clamp(amount, 0, 6),
    z = metal === 'Al' ? 3 : 2;
  const per = medium === 'acid' ? z : 1;
  const dissolved =
    medium === 'none' || (medium === 'base' && metal === 'Mg') ? 0 : Math.min(solid, input / per);
  return {
    metal,
    medium,
    prepared: solid,
    solid: solid - dissolved,
    dissolved,
    reagentUsed: dissolved * per,
    reagentLeft: input - dissolved * per,
    waterFormed: medium === 'acid' ? dissolved * z : 0,
    product: metal === 'Al' && medium === 'base' ? '[Al(OH)₄]⁻' : metal === 'Al' ? 'Al³⁺' : 'Mg²⁺',
    productCharge: medium === 'base' && metal === 'Al' ? -1 : z,
    centralOxidation: z,
    input,
    initialCharge: medium === 'acid' ? input : medium === 'base' ? -input : 0,
    finalCharge:
      medium === 'acid'
        ? dissolved * z + input - dissolved * per
        : medium === 'base'
          ? -dissolved - (input - dissolved)
          : 0,
  };
}
/** One net formula unit. Solid shown as composition box, NOT a molecule or crystal geometry. */
export function hydroxideNet(
  metal: HydroxideMetal,
  medium: 'acid' | 'base',
  progress: number,
  width = 300,
) {
  const w = clamp(width, 260, 900),
    p = medium === 'base' && metal === 'Mg' ? 0 : clamp(progress),
    z = metal === 'Al' ? 3 : 2;
  const mx = w * 0.26,
    startY = 106,
    travel = span(p, 0.22, 0.82),
    metalMove = span(p, 0.68, 1);
  const atoms: NetAtom[] = [
    {
      id: metal,
      element: metal,
      x: mix(mx + 25, w * 0.73, metalMove),
      y: startY,
      charge: z,
      phase: p >= 0.95 ? 'aqueous' : 'solid',
    },
  ];
  for (let i = 0; i < z; i++) {
    const sy = 51 + i * 49,
      sx = mx - 22,
      tx =
        medium === 'acid' ? w * 0.23 + i * w * 0.26 : w * 0.73 + (i === 0 ? 0 : i === 1 ? -33 : 33);
    const ty = medium === 'acid' ? 178 : i === 0 ? 56 : 148;
    atoms.push({
      id: `O${i}`,
      element: 'O',
      x: mix(sx, tx, travel),
      y: mix(sy, ty, travel),
      charge: -2,
      phase: p >= 0.95 ? 'aqueous' : 'solid',
    });
    atoms.push({
      id: `H${i}-solid`,
      element: 'H',
      x:
        medium === 'base'
          ? mix(sx, tx, travel) + (i === 2 ? 17 : -17)
          : mix(sx - 17, tx - 14, travel),
      y:
        medium === 'base'
          ? mix(sy, ty, travel) + (i === 0 ? -12 : 12)
          : mix(sy - 12, ty - 14, travel),
      charge: 1,
      phase: p >= 0.95 ? 'aqueous' : 'solid',
    });
    if (medium === 'acid')
      atoms.push({
        id: `H${i}-acid`,
        element: 'H',
        x: mix(w * 0.76 + (i - 1) * 24, tx + 14, travel),
        y: mix(45, ty - 14, travel),
        charge: 1,
        phase: 'aqueous',
      });
  }
  if (medium === 'base') {
    atoms.push({
      id: 'O-added',
      element: 'O',
      x: mix(w * 0.78, w * 0.73 + 33, travel),
      y: mix(48, 72, travel),
      charge: -2,
      phase: 'aqueous',
    });
    atoms.push({
      id: 'H-added',
      element: 'H',
      x: mix(w * 0.78 + 17, w * 0.73 + 47, travel),
      y: mix(34, 58, travel),
      charge: 1,
      phase: 'aqueous',
    });
  }
  return {
    atoms,
    z,
    progress: p,
    initialCharge: medium === 'acid' ? z : -1,
    charge: atoms.reduce((s, a) => s + a.charge, 0),
    finished: p >= 0.95,
    formula:
      medium === 'acid'
        ? `${metal}${z === 3 ? '³' : '²'}⁺ + ${z}H₂O`
        : metal === 'Al'
          ? '[Al(OH)₄]⁻'
          : 'Mg(OH)₂ + OH⁻',
  };
}

/** A single proton transfer in NH3 + H2O ⇌ NH4+ + OH−; H remains identifiable. */
export function ammoniaProton(progress: number, width = 300) {
  const w = clamp(width, 260, 900),
    p = clamp(progress),
    m = span(p, 0.15, 0.85);
  return {
    x: mix(w * 0.25 + 18, w * 0.73 - 25, m),
    y: mix(97, 111, m),
    transferred: p >= 0.85,
    waterCharge: p >= 0.85 ? -1 : 0,
    ammoniaCharge: p >= 0.85 ? 1 : 0,
    totalCharge: 0,
  };
}

