/** A smooth didactic clock within a selected net event, not a chemical rate law. */
function eventClock(t: number, points: readonly (readonly [number, number])[]) {
  if (t <= points[0][0]) return points[0][1];
  for (let i = 1; i < points.length; i++) {
    const [end, value] = points[i],
      [start, previous] = points[i - 1];
    if (t < end) return mix(previous, value, span(t, start, end));
  }
  return points[points.length - 1][1];
}
/** Actual word times plus the 0.45 s cue lead; direct seeking has no history dependence. */
export function periodicDirector(
  chapter: number,
  progress: number,
  chapterTime?: number,
  locale: 'zh' | 'en' = 'zh',
) {
  const c = Math.round(clamp(chapter, 0, 7)),
    en = locale === 'en',
    t =
      chapterTime === undefined
        ? clamp(progress) * PERIODIC_MEASURED_SECONDS[c]
        : clamp(chapterTime, 0, PERIODIC_MEASURED_SECONDS[c]);
  let shot = 'sample',
    event = 0,
    reveal = false,
    focus: HydroxideMetal = 'Mg';
  if (c === 0) {
    const entry = en ? 9.0 : 8.0,
      record = en ? 23.8 : 20.9;
    shot = t < entry ? 'sample' : t < record ? 'electrons' : 'evidence';
    event = en ? span(t, 10.0, 18.3) : span(t, 8.3, 15.8);
    reveal = t >= record;
  }
  if (c === 1) {
    const entry = en ? 6.55 : 6.7,
      finish = en ? 11.0 : 10.7,
      record = en ? 21.8 : 19.95;
    shot = t < entry ? 'sample' : t < finish ? 'electrons' : t < record ? 'sample' : 'evidence';
    event = en ? span(t, 6.6, 10.8) : span(t, 6.8, 10.5);
    reveal = t >= record;
  }
  if (c === 2) {
    const entry = en ? 3.8 : 3.5,
      rank = en ? 8.0 : 8.1,
      question = en ? 15.03 : 13.91,
      answer = en ? 21.25 : 19.77;
    shot =
      t < entry
        ? 'sample'
        : t < rank
          ? 'electrons'
          : t < question
            ? 'rank'
            : t < answer
              ? 'reverse-question'
              : 'reverse-answer';
    event = span(t, entry, rank - 0.2);
    reveal = t >= answer;
  }
  if (c === 3) {
    const surface = en ? 14.73 : 14.17,
      question = en ? 27.83 : 27.21;
    shot = t < surface ? 'cold' : t < question ? 'surface' : 'warm-question';
    event = span(t, surface, question);
  }
  if (c === 4) {
    const entry = en ? 3.29 : 3.61,
      account = en ? 21.13 : 17.99;
    shot = t < entry ? 'warm' : t < account ? 'magnesium-net' : 'magnesium-account';
    event = en
      ? eventClock(t, [
          [3.3, 0],
          [5.2, 0.2],
          [12.6, 0.75],
          [20.6, 1],
        ])
      : eventClock(t, [
          [3.6, 0],
          [5.0, 0.2],
          [10.9, 0.75],
          [17.6, 1],
        ]);
    reveal = t >= account;
  }
  if (c === 5) {
    const entry = en ? 5.29 : 5.81,
      stocks = en ? 14.95 : 14.33;
    shot = t < entry ? 'precipitate' : t < stocks ? 'ammonia' : 'stocks';
    event = en ? span(t, 7.4, 14.3) : span(t, 8.2, 13.8);
    reveal = t >= stocks;
  }
  if (c === 6) {
    const entry = en ? 8.59 : 7.55,
      aluminium = en ? 17.7 : 13.1,
      question = en ? 21.33 : 17.81,
      answer = en ? 25.85 : 21.85;
    shot =
      t < entry
        ? 'acid-observation'
        : t < question
          ? 'acid-net'
          : t < answer
            ? 'acid-question'
            : 'acid-limit';
    focus = t < aluminium ? 'Mg' : 'Al';
    event =
      focus === 'Mg'
        ? span(t, entry + 0.2, aluminium - 0.5)
        : span(t, aluminium + 0.1, question - 0.25);
    reveal = t >= answer;
  }
  if (c === 7) {
    const entry = en ? 10.43 : 8.15,
      question = en ? 27.95 : 23.07,
      answer = en ? 32.23 : 27.21,
      period = en ? 35.35 : 29.23;
    shot =
      t < entry
        ? 'base-observation'
        : t < question
          ? 'base-net'
          : t < answer
            ? 'base-question'
            : t < period
              ? 'base-answer'
              : 'period';
    event = en ? span(t, 12.7, 17.5) : span(t, 9.7, 14.3);
    reveal = t >= answer;
  }
  return {
    chapter: c,
    time: t,
    shot,
    event,
    reveal,
    focus,
    mode: c < 3 ? 'halogen' : c < 5 ? 'magnesium' : 'hydroxide',
    oxidant: (c === 2 ? 'Br' : 'Cl') as Halogen,
    halide: (c === 0 ? 'Br' : 'I') as Halogen,
    progress: span(t, c === 2 ? 0.8 : en ? 3.4 : 3.0, c === 2 ? 3.4 : en ? 5.9 : 5.6),
    available: 0.5,
    hot: c === 4,
    prepared: c === 5 ? span(t, 0.8, en ? 4.8 : 5.2) : 1,
    medium: (c === 6 ? 'acid' : c === 7 ? 'base' : 'none') as TestMedium,
    amount: c === 6 ? 3 : c === 7 ? 1 : 0,
  };
}
